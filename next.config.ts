import type { NextConfig } from "next";

/**
 * CSP diseñada para las dependencias reales de este proyecto: no hay scripts,
 * estilos ni imágenes de terceros. Next.js App Router necesita
 * 'unsafe-inline' en script-src para su script de hidratación (los datos de
 * React Server Components) y en style-src para los estilos en línea que
 * agrega next/image. No se usa un nonce dinámico a propósito: eso obligaría
 * a renderizar todo el sitio en modo dinámico (una petición por nonce) en un
 * sitio que es 100% informativo y estático por diseño.
 */
const contentSecurityPolicy = [
  "default-src 'self'",
  "script-src 'self' 'unsafe-inline'",
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data:",
  "font-src 'self'",
  "connect-src 'self'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'none'",
  "upgrade-insecure-requests",
].join("; ");

const securityHeaders = [
  { key: "Content-Security-Policy", value: contentSecurityPolicy },
  {
    key: "Strict-Transport-Security",
    value: "max-age=63072000; includeSubDomains; preload",
  },
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "X-Frame-Options", value: "DENY" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  {
    key: "Permissions-Policy",
    value: "camera=(), microphone=(), geolocation=(), interest-cohort=()",
  },
];

const nextConfig: NextConfig = {
  images: {
    formats: ["image/avif", "image/webp"],
  },
  async headers() {
    return [
      {
        source: "/:path*",
        headers: securityHeaders,
      },
    ];
  },
};

export default nextConfig;
